export function findProfileByCredentials(
  surname: string,
  phone: string,
): ErpProfile | undefined {
  const normalized = surname.toLowerCase().trim();
  const normalizedPhone = phone.replace(/\s/g, "");
  return erpProfiles.find(
    (p) =>
      p.surname.toLowerCase() === normalized &&
      p.phone.replace(/\s/g, "") === normalizedPhone,
  );
}

export function findProfileByPhone(phone: string): ErpProfile | undefined {
  const normalizedPhone = phone.replace(/\s/g, "");
  return erpProfiles.find(
    (p) => p.phone.replace(/\s/g, "") === normalizedPhone,
  );
}

export function findProfileById(id: string): ErpProfile | undefined {
  return erpProfiles.find((p) => p.id === id);
}

export function getCompaniesForProfile(profile: ErpProfile): Company[] {
  if (profile.visibleCompanyIds.includes("*")) return companies;
  return companies.filter((c) => profile.visibleCompanyIds.includes(c.id));
}

function filterByCompanyIds<T extends { companyId: string }>(
  items: T[],
  companyIds: string[],
): T[] {
  if (companyIds.includes("*")) return items;
  return items.filter((i) => companyIds.includes(i.companyId));
}

export function getDataForProfile(profile: ErpProfile) {
  const ids = profile.visibleCompanyIds;
  return {
    profile,
    companies: getCompaniesForProfile(profile),
    invoices: filterByCompanyIds(invoices, ids),
    bankTransactions: filterByCompanyIds(bankTransactions, ids),
    taxReturns: filterByCompanyIds(taxReturns, ids),
    payrollRecords: filterByCompanyIds(payrollRecords, ids),
    documents: filterByCompanyIds(documents, ids),
    deadlines: filterByCompanyIds(deadlines, ids),
    communicationLog: filterByCompanyIds(communicationLog, ids),
    riskAlerts: filterByCompanyIds(riskAlerts, ids),
    germanTaxCases: filterByCompanyIds(germanTaxCases, ids),
    workflows: filterByCompanyIds(workflows, ids),
    certificates,
    schEmployees: profile.role === "owner" ? schEmployees : [],
    auditLog:
      profile.role === "owner"
        ? auditLog
        : auditLog.filter((l) => l.userId === profile.id),
    cashFlowForecasts:
      ids.includes("*") || ids.includes("comp_montservis")
        ? cashFlowForecasts
        : [],
    agingBuckets:
      ids.includes("*") || ids.includes("comp_montservis") ? agingBuckets : [],
  };
}
